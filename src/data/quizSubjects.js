// Helper: get subject by slug
export function getSubjectBySlug(slug) {
  return QUIZ_SUBJECTS.find((s) => s.slug === slug) || null;
}

// Helper: get topic by subject slug + topic slug
export function getTopicBySlug(subjectSlug, topicSlug) {
  const subject = getSubjectBySlug(subjectSlug);
  if (!subject) return null;
  return subject.topics.find((t) => t.slug === topicSlug) || null;
}

// Helper: get next topic after current one (for "Next Topic" button)
export function getNextTopic(subjectSlug, topicSlug) {
  const subject = getSubjectBySlug(subjectSlug);
  if (!subject) return null;
  const idx = subject.topics.findIndex((t) => t.slug === topicSlug);
  if (idx === -1 || idx === subject.topics.length - 1) return null;
  return { subject, topic: subject.topics[idx + 1] };
}
